#pragma once

#include <cstdint>
#include <string>
#include <vector>

// Панель, которая перерисовывается на месте.
//
// Две совершенно разные жизни в зависимости от того, куда идёт вывод:
//
//   терминал  — панель на несколько строк, курсор возвращается наверх и
//               строки переписываются. Это то, ради чего всё затевалось:
//               видно карту тома, список получателей и скорость разом;
//
//   не терминал (перенаправление, systemd, `| tee`) — ни одной управляющей
//               последовательности. Вместо перерисовки раз в 15 секунд
//               печатается одна строка состояния. Журнал, забитый
//               миллионом строк «49,9 %», никому не нужен.
class LivePanel
{
public:
    void update(const std::vector<std::string> &lines);

    // Оставить последнее состояние на экране и отпустить курсор.
    void finish();

private:
    int m_printed = 0;
    int64_t m_lastPlainMs = 0;
    bool m_cursorHidden = false;
};
