#pragma once

#include <cstdint>
#include <string>
#include <vector>

// Панель, которая перерисовывается на месте.
//
// Две совершенно разные жизни в зависимости от того, куда идёт вывод:
//
//   терминал  — панель на несколько строк, курсор возвращается наверх и
//               строки переписываются. Это то, ради чего всё затевалось:
//               видно карту тома, список получателей и скорость разом;
//
//   не терминал (перенаправление, systemd, `| tee`) — ни одной управляющей
//               последовательности. Вместо перерисовки раз в 15 секунд
//               печатается одна строка состояния. Журнал, забитый
//               миллионом строк «49,9 %», никому не нужен.
//
// Перерисовка ограничена по частоте, и это не косметика, а
// производительность. Вызывающий зовёт update() из главного цикла, то есть
// сколько угодно раз в секунду; запись в консоль Windows — синхронный
// вызов к conhost, десятки миллисекунд на пачку управляющих
// последовательностей. Без ограничения приём упирался не в сеть, а в
// отрисовку прогресса приёма. Глазу больше десяти кадров в секунду от
// цифр всё равно не нужно.
class LivePanel
{
public:
    void update(const std::vector<std::string> &lines);

    // Оставить последнее состояние на экране и отпустить курсор.
    // Отложенный кадр, если он есть, дорисовывается здесь: иначе панель
    // застыла бы на предпоследнем состоянии и показывала 99 % у
    // завершённой передачи.
    void finish();

private:
    void draw(const std::vector<std::string> &lines);

    int m_printed = 0;
    int64_t m_lastPlainMs = 0;
    int64_t m_lastDrawMs = 0;
    bool m_cursorHidden = false;
    bool m_dirty = false;                 // есть непоказанный кадр
    std::vector<std::string> m_last;      // он же
};
