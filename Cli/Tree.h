#pragma once

#include <string>
#include <vector>

#include "core/Manifest.h"

// Обход каталога в опись тома (§3).
//
// Живёт у клиента, а не в ядре, ровно по одной причине: ядро не ходит в
// файловую систему. Разбор и проверка описи — в ядре (Manifest), а
// добывание её с диска — здесь.
namespace ferry::cli {

struct TreeScan
{
    Manifest manifest;

    // То, что пропустили и о чём человеку надо сказать вслух: симлинки,
    // файлы без доступа, узлы неизвестного вида. Молчаливо пропустить их
    // нельзя — том приедет неполным, а получатель об этом не узнает.
    std::vector<std::string> skipped;

    uint64_t fileCount = 0;
    uint64_t dirCount = 0;
};

// root — путь к каталогу. Имя тома берётся из последнего сегмента.
//
// false — обход не удался, причина в err. Это именно отказ, а не
// «сколько успели»: отправить половину дерева, не сказав об этом, хуже,
// чем не отправить ничего.
bool scanTree(const std::string &root, TreeScan &out, std::string *err);

} // namespace ferry::cli
