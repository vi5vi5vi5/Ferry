// `ferry uninstall` — убрать за собой всё.
//
// Обещание здесь такое же строгое, как у сервера: Ferry ничего не
// оставляет на диске сверх того, что положил установщик. Значит список
// следов конечен, известен поимённо и может быть показан человеку
// целиком, а не «мы там что-то почистили».
//
// Что убираем:
//   • каталог настроек (~/.config/ferry или %APPDATA%\ferry);
//   • запись в PATH пользователя — только Windows, потому что только там
//     установщик её делает;
//   • сам бинарь и каталог, в котором он лежит.
//
// Чего НЕ убираем и почему. Недокачки (`*.ferry-part`, `*.ferry-map`)
// лежат там, куда человек их скачивал, — по всему диску их не ищем: это
// его файлы в его каталогах, и молча удалять их страшнее, чем оставить.
// Строку про PATH в чужом ~/.profile тоже не трогаем: её туда дописывал
// человек, а не мы.
namespace ferry::cli {

int runUninstall(const Options &options);

} // namespace ferry::cli
