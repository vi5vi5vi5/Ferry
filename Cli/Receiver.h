namespace ferry::cli {

// `ferry get "<ссылка>"`: расшифровать метаданные, показать, что за том,
// и принять его на диск.
//
// Приём идёт через pwrite по смещению, а не потоком в конец файла. В M1
// чанки приходят по порядку и разницы не видно, но именно это делает
// возможными две волны и докачку в M2 — а битовая карта принятого пишется
// уже сейчас, чтобы работа не терялась.
int runGet(const Options &options);

} // namespace ferry::cli
