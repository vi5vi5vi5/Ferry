#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include "Manifest.h"

// Раскладка тома: какой байт какому файлу принадлежит.
//
// Том — это конкатенация файлов в порядке описи, без выравнивания и без
// заголовков между ними (§3). Сервер об этом не знает вовсе: он видит
// линейный поток чанков и одинаково возит им и один файл, и сорок тысяч.
// Вся разница живёт здесь, на обоих концах провода.
//
// Именно поэтому раскладка лежит в ядре, а не у отправителя. Разойдись
// две реализации на один байт — и получатель разложит том по файлам не
// так, как его собирали. Хеши при этом сойдутся (чанки-то те же), а файлы
// на диске окажутся склеены со сдвигом. Такую ошибку ищут вечер.
namespace ferry {

class VolumeLayout
{
public:
    // Кусок чанка, лежащий целиком внутри одного файла.
    struct Piece
    {
        size_t file = 0;        // индекс в files()
        uint64_t offset = 0;    // смещение ВНУТРИ файла
        uint64_t length = 0;
    };

    struct FileSpan
    {
        std::string path;       // относительный POSIX-путь
        uint64_t size = 0;
        uint64_t start = 0;     // смещение начала файла в томе
        int64_t mtime = 0;
    };

    // Раскладка по манифесту. Для kind == "file" получается один файл во
    // весь том — так обе ветки клиента ходят одной дорогой.
    //
    // Пустые директории и файлы нулевой длины в раскладку не попадают:
    // байт они не несут. Создавать их получателю всё равно надо, но это
    // дело манифеста, а не раскладки.
    void build(const Manifest &manifest);

    uint64_t total() const { return m_total; }
    const std::vector<FileSpan> &files() const { return m_files; }
    bool empty() const { return m_files.empty(); }

    // Разложить диапазон тома [from, from + length) по файлам.
    //
    // Пустой результат означает, что диапазон выходит за том, — и это
    // ошибка вызывающего, а не пустой ответ: на границе тома последний
    // чанк короче, и длину для него считает ChunkPlan, а не мы.
    std::vector<Piece> slice(uint64_t from, uint64_t length) const;

private:
    std::vector<FileSpan> m_files;
    uint64_t m_total = 0;
};

} // namespace ferry
