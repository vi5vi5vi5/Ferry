#pragma once

#include <cstddef>
#include <cstdint>
#include <vector>

// Множество чанков: «какие части тома у меня есть».
//
// Нужно обеим сторонам, и поэтому живёт в ядре. Сервер держит таким
// множеством карту каждого получателя, чтобы знать, у кого просить
// недостающий кусок (§6 проектного документа, reflected backfill).
// Получатель — свою карту принятого, ту самую, что лежит рядом с
// недокачкой в `.ferry-map`.
//
// Одна реализация на оба конца не из экономии: **диапазоны ездят по
// проводу**. Разойдись две реализации в трактовке границ хотя бы на
// единицу — и ошибка проявится не исключением, а дыркой в томе у
// получателя, через полчаса после начала перевоза.
//
// Чего здесь НЕТ сознательно: разбора JSON. Клиент пользуется своим
// json::Value, сервер — QJsonArray, и тащить любой из них в ядро значило
// бы тащить его же и в другой бинарь. Общее здесь — смысл диапазонов и
// операции над множеством; кодирование каждая сторона делает своим.
namespace ferry {

// Диапазон чанков. Границы ВКЛЮЧИТЕЛЬНЫЕ с обеих сторон: [5,5] — это
// ровно один чанк, [0,3] — четыре.
//
// Именно так записаны диапазоны в §8 проектного документа, и менять это
// нельзя: полуоткрытый интервал привычнее в C++, но он разъехался бы с
// протоколом, а протокол — то, по чему однажды напишут чужой клиент.
struct ChunkRange
{
    uint64_t from = 0;
    uint64_t to = 0;

    uint64_t size() const { return to >= from ? to - from + 1 : 0; }
    bool valid() const { return to >= from; }
    bool operator==(const ChunkRange &other) const
    {
        return from == other.from && to == other.to;
    }
};

class ChunkSet
{
public:
    ChunkSet() = default;
    explicit ChunkSet(uint64_t count) { reset(count); }

    // Завести множество на count чанков, всё пусто.
    void reset(uint64_t count);

    uint64_t count() const { return m_count; }

    bool has(uint64_t index) const;

    // true, если бит действительно изменился. Повторная установка — не
    // ошибка: чанк вполне может приехать дважды (живой поток и backfill
    // разошлись в гонке), и звать это ошибкой значило бы ронять передачу
    // на ровном месте.
    bool set(uint64_t index);
    bool clear(uint64_t index);

    // false — диапазон не помещается в том. Ничего при этом не меняется.
    bool setRange(const ChunkRange &range);

    // Применить список диапазонов ЦЕЛИКОМ или не применять вовсе.
    //
    // Всё-или-ничего здесь принципиально: список приходит по сети от
    // другой стороны. Применив половину и споткнувшись на второй, мы
    // получили бы карту, которой нет ни у кого, — и дальше спорили бы с
    // собеседником о том, что у него есть.
    bool applyRanges(const std::vector<ChunkRange> &ranges);

    // Сколько чанков есть. Считается по ходу, а не обходом карты: у тома
    // в терабайт это четверть миллиона бит, и спрашивают об этом на
    // каждом обороте цикла.
    uint64_t cardinality() const { return m_have; }

    // Сколько чанков подряд есть с начала.
    uint64_t prefix() const;

    bool empty() const { return m_have == 0; }
    bool full() const { return m_count != 0 && m_have == m_count; }

    // Что есть и чего нет, диапазонами. Обе всегда отсортированы и
    // склеены: соседние диапазоны не возвращаются по отдельности.
    std::vector<ChunkRange> ranges() const;
    std::vector<ChunkRange> missing() const;

    // Первый отсутствующий чанк, начиная с from. count(), если таких нет.
    uint64_t firstMissing(uint64_t from = 0) const;

    // Сырые байты карты — для хранения рядом с недокачкой. Порядок бит
    // внутри байта младшим вперёд (бит 0 — чанк 0), и трогать его нельзя:
    // в этом виде карта уже лежит на дисках у недокачек с M1.
    const std::vector<uint8_t> &bits() const { return m_bits; }
    size_t byteCount() const { return m_bits.size(); }

    // Поднять карту из сырых байт. Длина обязана совпасть с byteCount().
    //
    // Хвостовые биты за пределами count() гасятся молча: карта могла
    // прийти с диска, а на диске бывает что угодно, и ненулевой мусор в
    // последнем байте иначе посчитался бы чанками, которых в томе нет.
    bool loadBits(const uint8_t *data, size_t len);

    // Отсортировать, склеить пересекающиеся и соседние, проверить
    // границы. false — список негодный (перевёрнутый диапазон или выход
    // за пределы тома), и тогда ranges остаётся нетронутым.
    static bool normalize(std::vector<ChunkRange> &ranges, uint64_t count);

private:
    std::vector<uint8_t> m_bits;
    uint64_t m_count = 0;
    uint64_t m_have = 0;
};

} // namespace ferry
