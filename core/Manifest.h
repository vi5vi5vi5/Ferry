#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include "Types.h"

// Манифест тома (§3). Сервер его НЕ ЧИТАЕТ: до сервера он доезжает
// зашифрованным K_meta и для него это непрозрачные байты. Отсюда следует
// приятное: имени файла, количества файлов и структуры дерева сервер не
// знает вовсе, а `root` (он же content-id) тоже лежит внутри — иначе две
// раздачи одного и того же файла сопоставлялись бы между собой.
namespace ferry {

struct ManifestEntry
{
    std::string path;     // относительный POSIX-путь: "src/main.cpp"
    uint64_t size = 0;
    int64_t mtime = 0;    // unix-секунды; 0 — не знаем
    bool isDir = false;   // пустая директория: в том байт не вносит
};

struct Manifest
{
    int version = 1;
    std::string kind = "file";   // "file" | "tree"
    std::string name;            // имя файла или корневой папки
    uint64_t total = 0;          // байт в томе
    Hash32 root{};               // BLAKE3 над списком хешей чанков
    std::vector<ManifestEntry> entries;   // только для kind == "tree"

    bool isTree() const { return kind == "tree"; }

    std::string toJson() const;

    // err получает человекочитаемую причину. Разбор строгий: манифест —
    // это то, по чему получатель будет создавать файлы на своём диске,
    // поэтому «почти правильный» манифест отвергается целиком, а не чинится.
    static bool fromJson(const std::string &text, Manifest &out, std::string *err);
};

// Санитизация пути из манифеста (§3, класс уязвимостей Zip Slip).
//
// Отвергаем, а не «чиним»: молча исправленный путь означает, что файл лёг
// не туда, куда указано в манифесте, а значит хеш сойдётся, а дерево на
// диске будет не тем, что отправляли. Лучше отказать вслух.
//
// Проверяется: непустота, отсутствие ведущего слэша, сегментов "." и "..",
// обратных слэшей, буквы диска, управляющих символов и знаков < > : " | ? *,
// завершающих точек и пробелов в сегментах, резервных имён Windows
// (CON, PRN, AUX, NUL, COM1..9, LPT1..9).
bool sanitizeRelPath(const std::string &path, std::string *err = nullptr);

// Имя одиночного файла для kind == "file". Здесь мы, наоборот, ЧИНИМ:
// отправитель мог послать что угодно, включая путь целиком, а получателю
// нужно одно безопасное имя в выбранной им папке. Пустой результат
// означает, что из имени не осталось ничего пригодного.
std::string safeFileName(const std::string &name);

} // namespace ferry
