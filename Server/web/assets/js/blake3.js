// Рабочие буферы — один набор на модуль. JavaScript однопоточен внутри
// воркера, и выделять их на каждый вызов значило бы кормить сборщик мусора
// на каждом чанке.
const tail64 = new Uint32Array(16);           // неполный последний блок
const tail64b = new Uint8Array(tail64.buffer);
const cvBuf = new Uint32Array(8);              // цепочка текущего куска
const parentBlock = new Uint32Array(16);       // левый ‖ правый для узла дерева
const stack = new Uint32Array(54 * 8);         // 2^54 кусков — больше, чем бывает

// Сжать один кусок (до 1024 байт). words — Uint32Array всего входа,
// wordOff — где начинается кусок, len — его длина в байтах.
function chunkCv(bytes, words, byteOff, len, counter, extraFlags, out, outOff) {
    cvBuf.set(IV);
    const blocks = len === 0 ? 1 : Math.ceil(len / BLOCK_LEN);
    const ctrLo = counter >>> 0;
    const ctrHi = Math.floor(counter / 0x100000000) >>> 0;
    for (let j = 0; j < blocks; j++) {
        const start = byteOff + j * BLOCK_LEN;
        const blen = Math.min(BLOCK_LEN, len - j * BLOCK_LEN);
        let flags = 0;
        if (j === 0)
            flags |= CHUNK_START;
        const last = j === blocks - 1;
        if (last)
            flags |= CHUNK_END | extraFlags;
        const dst = last ? out : cvBuf;
        const dstOff = last ? outOff : 0;
        if (blen === BLOCK_LEN) {
            compress(cvBuf, 0, words, start >>> 2, ctrLo, ctrHi, BLOCK_LEN, flags, dst, dstOff);
        } else {
            tail64.fill(0);
            if (blen > 0)
                tail64b.set(bytes.subarray(start, start + blen));
            compress(cvBuf, 0, tail64, 0, ctrLo, ctrHi, blen, flags, dst, dstOff);
        }
    }
}

function parentCv(left, leftOff, right, rightOff, flags, out, outOff) {
    parentBlock.set(left.subarray(leftOff, leftOff + 8), 0);
    parentBlock.set(right.subarray(rightOff, rightOff + 8), 8);
    compress(IV, 0, parentBlock, 0, 0, 0, BLOCK_LEN, PARENT | flags, out, outOff);
}

// BLAKE3(data) → 32 байта.
export function blake3(data) {
    let bytes = data instanceof Uint8Array ? data : new Uint8Array(data);
    // Слова читаются через Uint32Array, а ему нужно выравнивание на 4.
    // Расшифрованный чанк всегда начинается с нуля своего буфера, так что
    // копия здесь — редкость (срезы, собранные вручную).
    if (bytes.byteOffset & 3) {
        const copy = new Uint8Array(bytes.length);
        copy.set(bytes);
        bytes = copy;
    }
    const words = new Uint32Array(bytes.buffer, bytes.byteOffset, bytes.length >>> 2);
    const len = bytes.length;
    const outWords = new Uint32Array(8);

    const chunks = len === 0 ? 1 : Math.ceil(len / CHUNK_LEN);
    if (chunks === 1) {
        chunkCv(bytes, words, 0, len, 0, ROOT, outWords, 0);
        return new Uint8Array(outWords.buffer);
    }

    // Дерево по правилу эталона: после каждого куска, кроме последнего,
    // сливаем вершины стека столько раз, сколько нулей в конце номера.
    let depth = 0;
    const cv = new Uint32Array(8);
    for (let i = 0; i < chunks - 1; i++) {
        chunkCv(bytes, words, i * CHUNK_LEN, CHUNK_LEN, i, 0, cv, 0);
        let total = i + 1;
        while ((total & 1) === 0) {
            depth--;
            parentCv(stack, depth * 8, cv, 0, 0, cv, 0);
            total = Math.floor(total / 2);
        }
        stack.set(cv, depth * 8);
        depth++;
    }

    // Последний кусок — не корень (корнем будет родитель), затем стек
    // сворачивается сверху вниз; последний родитель получает ROOT.
    const lastOff = (chunks - 1) * CHUNK_LEN;
    chunkCv(bytes, words, lastOff, len - lastOff, chunks - 1, 0, cv, 0);
    while (depth > 0) {
        depth--;
        parentCv(stack, depth * 8, cv, 0, depth === 0 ? ROOT : 0, cv, 0);
    }
    outWords.set(cv);
    return new Uint8Array(outWords.buffer);
}
