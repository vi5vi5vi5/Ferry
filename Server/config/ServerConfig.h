#pragma once

#include <QString>
#include <QStringList>

#include "config/Log.h"

// Настройки сервера: файл `<config-dir>/ferry.conf` плюс переменные
// окружения. Сервер этот файл только ЧИТАЕТ — на диск он не пишет ничего и
// никогда (§10), включая собственные настройки.
//
// Зачем файл, а не только аргументы командной строки: аргументы в докере
// прибиты в CMD образа, и чтобы поменять размер окна, пришлось бы править
// docker-compose.yml — файл из репозитория, который затрёт следующий
// `git pull`. Конфиг лежит в томе и переживает и пересборку образа, и
// обновление из гита.
//
// Формат — INI: секции в квадратных скобках, `ключ = значение`, комментарии
// с `#` или `;`. Разбор свой, не QSettings: QSettings умеет переписать файл,
// растеряв комментарии, ради которых он и заводится.
//
// Окружение сильнее файла, аргументы командной строки сильнее окружения.
struct ServerConfig
{
    // ---- [server] ----
    // Имя инстанса. Видно в GET /api/health и в шапке CLI.
    QString name = QStringLiteral("Ferry");
    // Внешний адрес («https://ferry.example.ru»). Нужен, чтобы собрать
    // ссылку на раздачу: сам сервер за прокси своего имени не знает.
    // Пусто — клиент подставит тот адрес, по которому подключился.
    QString publicUrl;

    // ---- [transfer] ----
    // Окно на одну раздачу. Это буфер джиттера, а не кэш (§6): при 100 МБ/с
    // 256 МиБ покрывают две с половиной секунды разброса между получателями.
    int windowMb = 256;
    // Глобальный потолок памяти под все окна. При достижении новые раздачи
    // получают server_busy, а окна существующих ужимаются — своп для
    // релея хуже отказа, потому что он утягивает за собой всех сразу.
    int ramBudgetMb = 1024;
    // Сколько раздач живёт одновременно.
    int maxTransfers = 64;
    // Потолок получателей на раздачу. Отправитель может попросить меньше,
    // больше — нет: это защита от превращения VPS в раздатчик для форума.
    int maxConcurrent = 8;
    // Срок жизни раздачи по умолчанию и максимальный, в секундах.
    int defaultTtlS = 24 * 60 * 60;
    int maxTtlS = 7 * 24 * 60 * 60;

    // ---- [limits] ----
    // Анти-абьюз без хранения (§10): счётчики в оперативке, всё обнуляется
    // при перезапуске, никакой истории.
    int createPerIpPerMin = 10;
    int maxTransfersPerIp = 8;

    // ---- [web] ----
    // Раздавать ли страницы и установщик клиента. false — остаётся только
    // JSON API и WebSocket-релей.
    bool webEnabled = true;

    // ---- [log] ----
    Log::Level logLevel = Log::Level::Errors;

    // Производные, чтобы не пересчитывать в горячих местах.
    qint64 windowBytes() const { return qint64(windowMb) * 1024 * 1024; }
    qint64 ramBudgetBytes() const { return qint64(ramBudgetMb) * 1024 * 1024; }

    // Читает файл, затем накладывает окружение. Непонятые ключи и значения
    // не роняют запуск — о каждом говорится вслух и берётся умолчание:
    // сервер, который не поднялся из-за опечатки в необязательной настройке,
    // хуже сервера с умолчанием.
    // warnings получает то, о чём стоит сказать после установки журнала.
    static ServerConfig load(const QString &filePath, QStringList *warnings);
};
