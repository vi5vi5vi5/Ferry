#pragma once

#include <QByteArray>
#include <QHash>

// Выданные, но ещё не использованные challenge (§5).
//
// Зачем это вообще нужно. Сервер не знает ключа K и поэтому не может
// отличить настоящего получателя от бота, который дёрнул ссылку без
// фрагмента — а таких ботов в мессенджерах полно, они ходят по всем
// ссылкам ради превью. Если бы использование списывалось при подключении,
// первый же бот сжёг бы одноразовую ссылку раньше человека.
//
// Поэтому: сервер выдаёт случайные 16 байт, получатель отвечает
// HMAC-SHA256(V, challenge), где V он вывел из K сам. Сервер знает V (оно
// пришло в offer) и может проверить ответ, но получить из V ключ K не
// может — HKDF односторонний.
//
// Challenge одноразовый и живёт две минуты: иначе подслушанный ответ можно
// было бы предъявить повторно.
class ChallengeStore
{
public:
    QByteArray issue();

    // true — challenge наш, свежий и ещё не использованный. Второй вызов с
    // тем же значением вернёт false.
    bool consume(const QByteArray &challenge);

    void sweep();

    int size() const { return m_issued.size(); }

private:
    static constexpr qint64 kTtlMs = 2 * 60 * 1000;
    // Потолок на случай, если кто-то начнёт дёргать /challenge в цикле:
    // 100 000 записей по 48 байт — пять мегабайт, дальше просто перестаём
    // выдавать новые, а не растём до конца памяти.
    static constexpr int kMaxIssued = 100000;

    QHash<QByteArray, qint64> m_issued;   // challenge -> когда истекает
};
